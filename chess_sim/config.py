def piece_envelope(piece_type: str) -> List[Tuple[float, float, float]]:
    """Analytic collision envelope of a mesh piece: [(z0, z1, radius)] over the manifest's 10 height slices, the
    radius being the larger of half the slice's caliper width and the measured axis radius (vertices and exact
    cuts, PIECE_AXIS_RADIUS_MM) + ENVELOPE_PAD: a stack of discs containing the whole mesh surface."""
    p = PIECE_PROFILE[piece_type]
    ax = PIECE_AXIS_RADIUS_MM[piece_type]
    return [(z0, z1, max(w / 2.0, ax[i] / 1000.0) + ENVELOPE_PAD) for i, (z0, z1, w) in enumerate(p["slices"])]


PIECE_ENVELOPE: Dict[str, List[Tuple[float, float, float]]] = {t: piece_envelope(t) for t in PIECE_TYPES}


def piece_radius_at(piece_type: str, z: float, collision: Optional[str] = None) -> float:
    """Collision radius (m) of a piece at height z above its base: the envelope ('bands') or the base / stem
    cylinder ('cylinders'); 0 outside the piece."""
    H, D, _ = PIECE_SPECS[piece_type]
    if z < 0.0 or z > H:
        return 0.0
    if (collision or PIECE_COLLISION_DEFAULT) == "cylinders":
        return D / 2.0 if z <= COLLISION_BASE_HEIGHT_FRAC * H else COLLISION_STEM_DIA_FRAC * D / 2.0
    for z0, z1, r in PIECE_ENVELOPE[piece_type]:
        if z <= z1:
            return r
    return PIECE_ENVELOPE[piece_type][-1][2]


def piece_height_within(piece_type: str, lateral: float, collision: Optional[str] = None) -> float:
    """Highest point (m above the base) of a piece whose collision radius reaches at least `lateral` from its axis
    (0 when nothing does): the obstacle height of a piece standing `lateral` away from a corridor's edge."""
    H, D, _ = PIECE_SPECS[piece_type]
    if (collision or PIECE_COLLISION_DEFAULT) == "cylinders":
        if lateral <= COLLISION_STEM_DIA_FRAC * D / 2.0:
            return H
        return COLLISION_BASE_HEIGHT_FRAC * H if lateral <= D / 2.0 else 0.0
    top = 0.0
    for z0, z1, r in PIECE_ENVELOPE[piece_type]:
        if r >= lateral:
            top = z1
    return top


def piece_max_radius(piece_type: str, z_from: float = 0.0, collision: Optional[str] = None) -> float:
    """Largest collision radius (m) of a piece at heights >= z_from (what a descending finger beside it must clear)."""
    H, D, _ = PIECE_SPECS[piece_type]
    if (collision or PIECE_COLLISION_DEFAULT) == "cylinders":
        return D / 2.0 if z_from < COLLISION_BASE_HEIGHT_FRAC * H else COLLISION_STEM_DIA_FRAC * D / 2.0
    return max([r for z0, z1, r in PIECE_ENVELOPE[piece_type] if z1 > z_from] or [0.0])


# Grasp table of the 'bands' collision model, derived by build_scene.grasp_table from the piece width profile
# (the mesh's 0.1 mm planar cuts, i.e. the geometry behind the manifest's stem profile and 10 slices, which are
# too coarse above 75 % of the height) and the measured finger-box levels (python -m chess_sim.build_scene
# --print-grasp; test_scene (a3) checks these numbers against a fresh derivation and the manifest).  Meaning: the
# fingertips (= the tool point) at `height` above the piece base; the pads (finger box 0: tip..tip + 10 mm) stall
# on `width` (the widest section inside the pad window); the open fixed finger descends `envelope`/2 + the side
# clearance from the piece axis (the widest section above the tips); `zone` is the range of tip heights with the
# same stall feature (the lower end is the carry fallback); `axis_deg` names a grasp axis in the piece frame for
# pieces that are not solids of revolution (the knight: across its head).  Rule (one test per tip height, 0.1 mm):
#   rigid hold: the pads must touch the piece over >= 4 mm of height (a cylinder, or two features that lock each
#     other), counting sections within 1.2 mm of the stall width (the soft contacts sink ~0.9 mm per side) and a
#     wider feature up to 0.8 mm below the tips (it stops the swing at the pad bottom edge); a single ring / ball
#     equator / rim between flat pads swings like a pendulum (measured 6..12 deg while carried);
#   no flare at the pad bottom edge steeper than 0.5 radius/height (the squeeze would push the piece up);
#   room above: finger box 1 (tip + 10..20 mm) and box 2 (tip + 20..40 mm), which at the stall are 2..3.5 mm and
#     6..11 mm wider than the pads (measured level table), must clear the collar / head above by 1 mm;
#   tips between 30 % and 70 % of the height, the pads overlapping the piece by >= 8 mm (no pinch on a top knob),
#     and below the IK reach cap (the king: 29.4 mm, above it a1/h1 need > 8 deg of lean);
#   then the narrowest stall width wins; its zone (same feature, width within 0.25 mm) is centred.
# Chosen heights (mm; physics probe: deviation after a 30 mm lift + a 40 mm lateral jerk, tilt while carried):
#   pawn   16.5 (66 %): the head ball (8.7 mm at 21 mm) with the 9.2 mm collar 0.75 mm under the tips as the stop
#                      (dev 1.9 mm, tilt 2.0 deg); the 4.6..5.7 mm stem (9..14 mm) has no 10 mm of room
#   rook   17.9 (64 %): the 15.7 mm battlement (22.5..28 mm) fills the pad top (tilt 3.3 deg); the 10.2 mm stem
#                      (16..20 mm) is 4 mm tall under it and box 1 cannot clear the battlement
#   knight 16.6 (54 %): across the head (y: 9.8..10.9 mm over 15..27 mm, a long near-cylinder; tilt < 1 deg at
#                      every yaw with the jaws within 25 deg of the axis); along the head the stall is 19.7 mm
#   bishop 21.7 (60 %): the mitre belly (12.9 mm at 25.8 mm) with the 14 mm collar 0.7 mm under the tips as the
#                      stop (tilt 2.6 deg; 0.5 mm higher the stop is lost and it swings 5..9 deg)
#   queen  23.1 (58 %): the 12.1 mm ring (26.5 mm) + the crown cone at the pad top edge lock each other (tilt
#                      0.7 deg); the 7.2 mm stem alone would put box 1 on the 13.9 mm crown
#   king   29.1 (58 %): the 11.4 mm collar ring (29..31.5 mm) + the 11 mm crown rim at the pad top edge (tilt 2.4
#                      deg; the collar alone, e.g. tips at 25 mm, swings 10 deg; the 6.4 mm stem puts box 1 on
#                      the collar); 29.4 mm is the a1/h1 reach limit (8 deg lean)
