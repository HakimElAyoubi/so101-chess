def _load_piece_manifest(path: str = PIECE_MANIFEST_JSON) -> Dict[str, dict]:
    """type -> dict(height, foot, slices [(z0, z1, max caliper width)], stem [(z, width)] (the exact planar cuts
    every 1 % of the height over 45..75 %), stem_min (width, z), above_foot (max width above the foot), triangles,
    vertices), all in metres, from the staged manifest."""
    try:
        with open(path) as f:
            man = json.load(f)
    except OSError as e:
        raise FileNotFoundError(f"piece mesh manifest missing: {path} (copy _archive/chess_sim_assets_staging/pieces/*)") from e
    out = {}
    for t, rec in man["pieces"].items():
        mm = rec["measured_mm"]
        H = mm["height"] / 1000.0
        out[t] = dict(
            height=H, foot=mm["foot_diameter_bottom_20pct"] / 1000.0,
            slices=[(s["z_from_mm"] / 1000.0, s["z_to_mm"] / 1000.0, s["max_xy_distance_mm"] / 1000.0) for s in mm["diameter_profile_10_slices"]],
            slices_x=[(s["z_from_mm"] / 1000.0, s["z_to_mm"] / 1000.0, s["x_extent_mm"] / 1000.0) for s in mm["diameter_profile_10_slices"]],
            slices_y=[(s["z_from_mm"] / 1000.0, s["z_to_mm"] / 1000.0, s["y_extent_mm"] / 1000.0) for s in mm["diameter_profile_10_slices"]],
            stem=[(p["height_pct"] / 100.0 * H, p["extent_mm"] / 1000.0) for p in mm["stem_profile_45_75pct"]],
            stem_min=(mm["stem_min_45_75pct"]["diameter"] / 1000.0, mm["stem_min_45_75pct"]["at_z_mm"] / 1000.0),
            above_foot=mm["above_foot_max_width"] / 1000.0,
            triangles=int(rec["mesh"]["triangles"]), vertices=int(rec["mesh"]["vertices"]),
            source=man["source"]["asset"], url=man["source"]["url"],
            scale=(rec["transforms"]["scale_factors"]["x"], rec["transforms"]["scale_factors"]["z"]))
    return out


