# --------------------------------------------------------------------------- unit helpers (LeRobot convention)
def deg2rad(x):
    return np.asarray(x, dtype=float) * math.pi / 180.0


def rad2deg(x):
    return np.asarray(x, dtype=float) * 180.0 / math.pi


# --------------------------------------------------------------------------- gripper (simulated jaw kinematics)
def gripper_gap(q):
    """Simulated FINGERTIP gap (m) for a gripper joint angle (rad): law of cosines of the measured JAW_MODEL."""
    J = JAW_MODEL
    th = J["theta0"] + (np.asarray(q, dtype=float) - J["q_closed"])
    g2 = J["dz"] ** 2 + J["r_fixed"] ** 2 + J["r_moving"] ** 2 - 2.0 * J["r_fixed"] * J["r_moving"] * np.cos(th)
    out = np.sqrt(np.maximum(g2, 0.0))
    return float(out) if np.ndim(out) == 0 else out


def gripper_ctrl_for_gap(gap: float) -> float:
    """Gripper joint angle / ctrl (rad) whose simulated fingertip gap is `gap` (m); clipped to the joint range."""
    J = JAW_MODEL
    gap = min(gripper_gap(J["q_open"]), max(gripper_gap(J["q_closed"]), float(gap)))
    c = (J["dz"] ** 2 + J["r_fixed"] ** 2 + J["r_moving"] ** 2 - gap ** 2) / (2.0 * J["r_fixed"] * J["r_moving"])
    q = J["q_closed"] + math.acos(min(1.0, max(-1.0, c))) - J["theta0"]
    return min(J["q_open"], max(J["q_closed"], q))


def gripper_clearance(q):
    """Simulated jaw CLEARANCE (m) at angle q: the widest stem that fits between the jaws (inner lips)."""
    out = np.interp(np.asarray(q, dtype=float), JAW_CLEARANCE_Q, JAW_CLEARANCE)
    return float(out) if np.ndim(out) == 0 else out


def gripper_ctrl_for_clearance(clearance: float) -> float:
    """Gripper joint angle (rad) at which the jaw clearance equals `clearance` (m): the angle the jaws stall at
    when closing on a stem of that diameter; clipped to the joint range."""
    return float(np.interp(float(clearance), JAW_CLEARANCE, JAW_CLEARANCE_Q))


def stem_diameter(piece_type: str, collision: Optional[str] = None) -> float:
    """Width (m) the jaws stall on when closing on a piece type at its grasp height: 'cylinders' the collision stem
    (0.6 x base diameter), 'bands' the widest section of the mesh inside the fingertip pads (GRASP_TABLE_BANDS)."""
    if (collision or PIECE_COLLISION_DEFAULT) == "cylinders":
        return COLLISION_STEM_DIA_FRAC * PIECE_SPECS[piece_type][1]
    return GRASP_TABLE_BANDS[piece_type]["width"]


def grasp_envelope_diameter(piece_type: str, collision: Optional[str] = None) -> float:
    """Diameter (m) the OPEN jaws must straddle to descend onto a piece: twice the largest collision radius at
    or above the grasp height (the fixed finger passes beside it); equals the stem for 'cylinders'."""
    if (collision or PIECE_COLLISION_DEFAULT) == "cylinders":
        return stem_diameter(piece_type, "cylinders")
    return GRASP_TABLE_BANDS[piece_type]["envelope"]


def gripper_close_ctrl(piece_type: str, collision: Optional[str] = None) -> float:
    """Close command for a piece type: ctrl whose fingertip gap = stall width - SQUEEZE (spec).  Since the jaw
    clearance is smaller than the fingertip gap, the jaws always stall on the piece (at gripper_stall_ctrl) with
    the position actuator pushing beyond it."""
    return gripper_ctrl_for_gap(stem_diameter(piece_type, collision) - SQUEEZE)


def gripper_stall_ctrl(piece_type: str, collision: Optional[str] = None) -> float:
    """Joint angle at which the closing jaws meet the piece (clearance = stall width); the measured gripper angle
    of a successful grasp is close to this value."""
    return gripper_ctrl_for_clearance(stem_diameter(piece_type, collision))


def gripper_open_ctrl() -> float:
    """Approach command: ctrl whose fingertip gap = APPROACH_GAP."""
    return gripper_ctrl_for_gap(APPROACH_GAP)


# percent end points (rad) for the selected mode
if GRIPPER_PERCENT_MODE == "measured_gap":
    GRIPPER_Q_PCT0 = gripper_ctrl_for_gap(GRIPPER_GAP_CLOSED)       # -0.169 rad (7 mm)
    GRIPPER_Q_PCT100 = gripper_ctrl_for_gap(GRIPPER_GAP_OPEN)       # +0.749 rad (80 mm)
elif GRIPPER_PERCENT_MODE == "joint_range":
    GRIPPER_Q_PCT0, GRIPPER_Q_PCT100 = GRIPPER_Q_CLOSED, GRIPPER_Q_OPEN
else:
    raise ValueError(f"unknown GRIPPER_PERCENT_MODE {GRIPPER_PERCENT_MODE!r}")


def gripper_frac_to_percent(q: float) -> float:
    """Gripper joint angle (rad, MJCF) -> LeRobot percent (0 closed .. 100 open), clipped to 0..100."""
    p = (float(q) - GRIPPER_Q_PCT0) / (GRIPPER_Q_PCT100 - GRIPPER_Q_PCT0) * 100.0
    return min(100.0, max(0.0, p))


def gripper_percent_to_frac(p: float) -> float:
    """LeRobot percent (0 closed .. 100 open) -> gripper joint angle (rad)."""
    p = min(100.0, max(0.0, float(p)))
    return GRIPPER_Q_PCT0 + p / 100.0 * (GRIPPER_Q_PCT100 - GRIPPER_Q_PCT0)


def gripper_percent_for_gap(gap: float) -> float:
    """LeRobot percent whose simulated fingertip gap is `gap` (m)."""
    return gripper_frac_to_percent(gripper_ctrl_for_gap(gap))


def gripper_gap_for_percent(p: float) -> float:
    """Simulated fingertip gap (m) at a LeRobot percent."""
    return gripper_gap(gripper_percent_to_frac(p))


def lerobot_to_qpos(vec6) -> np.ndarray:
    """[5 joints deg, gripper %] -> 6 joint angles (rad) in JOINT_NAMES order."""
    v = np.asarray(vec6, dtype=float)
    deg = v[:5] + (JOINT_ZERO_OFFSETS_DEG if APPLY_JOINT_OFFSETS else 0.0)
    return np.concatenate([deg2rad(deg), [gripper_percent_to_frac(v[5])]])


def qpos_to_lerobot(q6) -> np.ndarray:
    """6 joint angles (rad) -> [5 joints deg, gripper %]."""
    q = np.asarray(q6, dtype=float)
    deg = rad2deg(q[:5]) - (JOINT_ZERO_OFFSETS_DEG if APPLY_JOINT_OFFSETS else 0.0)
    return np.concatenate([deg, [gripper_frac_to_percent(q[5])]])


def grasp_height(piece_type: str, collision: Optional[str] = None) -> float:
    """Nominal fingertip (tool point) height above the piece base for a grasp: 'cylinders' GRASP_HEIGHT_FRAC x the
    height (the king's 50 % override lives in kinematics.grasp_height), 'bands' the table height."""
    if (collision or PIECE_COLLISION_DEFAULT) == "cylinders":
        return GRASP_HEIGHT_FRAC * PIECE_SPECS[piece_type][0]
    return GRASP_TABLE_BANDS[piece_type]["height"]


def piece_body_names() -> list:
    """The 34 free bodies: <colour>_<type>_<n> plus w_queen_spare_1 / b_queen_spare_1."""
    names = []
    for c in ("w", "b"):
        for t, n in PIECE_COUNTS.items():
            names += [f"{c}_{t}_{i + 1}" for i in range(n)]
        names.append(f"{c}_queen_spare_1")
    return names


def square_name(file_idx: int, rank: int) -> str:
    return "abcdefgh"[file_idx] + str(rank)


def square_index(name: str) -> Tuple[int, int]:
    """'e4' -> (file 4, rank 4)."""
    return "abcdefgh".index(name[0]), int(name[1])


def square_is_dark(file_idx: int, rank: int) -> bool:
    """a1 (file 0, rank 1) is dark."""
    return (file_idx + rank) % 2 == 1


