GRASP_ZONE_FALLBACK_MIN = 0.002   # a lower grasp inside the zone is tried only when it is this much lower (m)
GRASP_DZ_CYLINDERS = (0.0, 0.003) # 'cylinders': grasp height offsets the expert may choose between (still on the stem)
GRASP_DZ_MIN = 0.0003             # 'bands': a zone offset smaller than this is not worth a candidate (m)
# 'bands' last resort: +3 mm above the table height, OUTSIDE the grasp zone, tried only when no in-zone candidate
# clears the neighbours (crowded squares: the c8 bishop of the start position between the b7/c7/d7 pawn heads).
# The pads then pinch a single feature (bishop: the mitre belly without the collar stop; queen: the crown cone):
# measured hold 2.3 mm / 2 deg (bishop c8), 3.6 mm / 12 deg of swing (queen d8); the queen's crown-cone pinch
# toppled at a corner release, hence the tiering.
GRASP_DZ_LAST_RESORT = 0.003


def grasp_dz_candidates(piece_type: str, collision: Optional[str] = None) -> Tuple[float, ...]:
    """Vertical offsets (m) of the grasp tool point the expert's grasp_pose may choose between (it prefers the
    one with the larger neighbour clearance).  'cylinders': 0 and +3 mm (anywhere on the uniform stem).  'bands':
    only offsets inside the grasp zone (the heights that stall on the same feature): 0, the top and the bottom of
    the zone when they are >= GRASP_DZ_MIN away, then GRASP_DZ_LAST_RESORT as a lower-priority tier (see
    grasp_dz_tier).  Outside the zone the pads hold another feature: a queen grasped 3 mm high pinches its crown
    cone alone, swings 28 deg while carried and topples at the release (measured)."""
    if (collision or PIECE_COLLISION_DEFAULT) == "cylinders":
        return GRASP_DZ_CYLINDERS
    rec = GRASP_TABLE_BANDS[piece_type]
    out = [0.0]
    for z in (rec["zone_hi"], rec["zone_lo"]):
        dz = round(z - rec["height"], 6)
        if abs(dz) >= GRASP_DZ_MIN:
            out.append(dz)
    if GRASP_DZ_LAST_RESORT not in out:
        out.append(GRASP_DZ_LAST_RESORT)
    return tuple(out)


def grasp_dz_tier(piece_type: str, dz: float, collision: Optional[str] = None) -> int:
    """0 for a grasp height offset inside the grasp zone (or any 'cylinders' offset), 1 for the 'bands' last
    resort outside it: the expert prefers tier 0 whenever one of its candidates clears the neighbours."""
    if (collision or PIECE_COLLISION_DEFAULT) == "cylinders":
        return 0
    rec = GRASP_TABLE_BANDS[piece_type]
    return 0 if rec["zone_lo"] - 1e-9 <= rec["height"] + dz <= rec["zone_hi"] + 1e-9 else 1


def piece_side_extent(piece_type: str, theta_deg: Optional[float] = None, above: bool = False,
                      collision: Optional[str] = None) -> float:
    """How far (m) a piece reaches from its axis toward the direction theta (deg in the piece frame) at the
    grasp: inside the pad window (the side the pads stall on; above=False) or anywhere above the tips (what the
    open fixed finger must clear while descending; above=True).  Half the stall width / envelope for solids of
    revolution and for 'cylinders'; the directional table ('extent_mm', 10 deg steps) for the knight."""
    if (collision or PIECE_COLLISION_DEFAULT) == "cylinders":
        return stem_diameter(piece_type, "cylinders") / 2.0
    rec = GRASP_TABLE_BANDS[piece_type]
    ext = rec.get("extent_mm")
    if ext is None or theta_deg is None:
        return (rec["envelope"] if above else rec["width"]) / 2.0
    th = float(theta_deg) % 360.0
    i = int(th // 10.0)
    f = th / 10.0 - i
    a, b = ext[i][1 if above else 0], ext[(i + 1) % len(ext)][1 if above else 0]
    return max(a, b) / 1000.0 if f > 0.0 else a / 1000.0


def grasp_height_candidates(piece_type: str, collision: Optional[str] = None) -> List[Optional[float]]:
    """Grasp heights (m above the base; None = the nominal one) tried in turn by the expert for a pick-and-place:
    'cylinders': the spec height then 50 % / 40 % of the piece height (a lower grasp lets a carried piece pass
    over neighbours where the reach ceiling is low); 'bands': the table height then the lower end of its zone."""
    H = PIECE_SPECS[piece_type][0]
    if (collision or PIECE_COLLISION_DEFAULT) == "cylinders":
        return [None, 0.50 * H, 0.40 * H]
    rec = GRASP_TABLE_BANDS[piece_type]
    out: List[Optional[float]] = [None]
    if rec["zone_lo"] <= rec["height"] - GRASP_ZONE_FALLBACK_MIN:
        out.append(rec["zone_lo"])
    return out

